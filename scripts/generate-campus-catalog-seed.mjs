import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const jobsDir = path.join(root, 'docs', '秋招岗位');
const outFile = path.join(
  root,
  'supabase',
  'migrations',
  '20260831120001_seed_campus_job_catalog.sql'
);

function slugify(value) {
  return value
    .replace(/[^\w\u4e00-\u9fff-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

function buildJobId(company, position, location, disambiguator = '') {
  const base = `${slugify(company)}__${slugify(position)}__${slugify(location)}`;
  if (!disambiguator) {
    return base;
  }
  return `${base}__${slugify(disambiguator)}`;
}

function normalizeCategory(category) {
  const allowed = ['frontend', 'agent_dev', 'ai_fullstack', 'ai_app', 'other'];
  return allowed.includes(category) ? category : 'other';
}

function getTierFromMatch(qualified, confidence) {
  if (!qualified) return 'skip';
  if (confidence >= 0.95) return 'S';
  if (confidence >= 0.9) return 'A';
  if (confidence >= 0.8) return 'B';
  if (confidence >= 0.76) return 'edge';
  return 'skip';
}

function walkJsonFiles(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walkJsonFiles(fullPath));
    } else if (entry.isFile() && entry.name.endsWith('.json')) {
      files.push(fullPath);
    }
  }
  return files;
}

function toCampusJobData(raw, id) {
  const category = normalizeCategory(raw.match?.category || raw.extended?.job_category || 'other');
  return {
    id,
    source: 'builtin',
    basic: raw.basic,
    details: raw.details,
    extended: {
      ...raw.extended,
      job_category: category,
    },
    match: {
      ...raw.match,
      category,
    },
    tier: getTierFromMatch(raw.match.qualified, raw.match.confidence),
  };
}

function sqlEscapeJson(value) {
  return JSON.stringify(value).replace(/'/g, "''");
}

const files = walkJsonFiles(jobsDir);
const usedIds = new Set();
const jobs = files.map((filePath) => {
  const raw = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const fileStem = path.basename(filePath, '.json');
  const baseId = buildJobId(raw.basic.company, raw.basic.position, raw.basic.location);
  const id = usedIds.has(baseId)
    ? buildJobId(raw.basic.company, raw.basic.position, raw.basic.location, fileStem)
    : baseId;
  usedIds.add(id);
  const job = toCampusJobData(raw, id);
  return job;
});

jobs.sort((a, b) => a.id.localeCompare(b.id, 'zh-CN'));

const lines = [
  '-- Seed campus_job_catalog from docs/秋招岗位/*.json',
  '-- Generated by scripts/generate-campus-catalog-seed.mjs',
  '',
  'insert into public.campus_job_catalog (id, job_data, is_active, updated_at)',
  'values',
];

for (let i = 0; i < jobs.length; i += 1) {
  const job = jobs[i];
  const suffix = i === jobs.length - 1 ? '' : ',';
  lines.push(
    `  ('${job.id}', '${sqlEscapeJson(job)}'::jsonb, true, now())${suffix}`
  );
}

lines.push(
  'on conflict (id) do update set',
  '  job_data = excluded.job_data,',
  '  is_active = excluded.is_active,',
  '  updated_at = excluded.updated_at;'
);

fs.writeFileSync(outFile, `${lines.join('\n')}\n`, 'utf8');
console.log(`Wrote ${jobs.length} jobs to ${outFile}`);
